// Today's base date helper
const now = new Date();
const addDays = (days: number) => {
  const d = new Date(now.getTime() + days * 86400000);
  return d.toISOString().split('T')[0];
};
const subDays = (days: number) => {
  const d = new Date(now.getTime() - days * 86400000);
  return d.toISOString().split('T')[0];
};

